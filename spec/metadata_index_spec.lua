local helpers = require("spec.test_helpers")
local errors = require("compile-mode.errors")
local cdir = require("compile-mode.dir")
local state = require("compile-mode.state")
local statusline = require("compile-mode.statusline")
local navigation = require("compile-mode.navigation")

local function error_at(line, filename, level)
	local error = assert(errors.parse((filename or "main.c") .. ":12:3: error: failure", line))
	error.level = level or errors.level.ERROR
	return error
end

describe("compilation metadata indexes", function()
	before_each(function()
		helpers.setup_tests()
		state.reset()
		cdir.compilation_directory = vim.fn.getcwd()
	end)

	it("indexes out-of-order directory edits with strict preceding-line semantics", function()
		cdir.set_directory(10, "/ten")
		cdir.set_directory(4, "/four")
		cdir.set_directory(7, "/seven")
		assert.are.equal(cdir.compilation_directory, cdir.find_directory_for_line(4))
		assert.are.equal("/four", cdir.find_directory_for_line(7))
		assert.are.equal("/seven", cdir.find_directory_for_line(10))
		assert.are.equal("/ten", cdir.find_directory_for_line(11))
		cdir.set_directory(7, "/replacement")
		assert.are.equal("/replacement", cdir.find_directory_for_line(9))
		cdir.set_directory(7, nil)
		assert.are.equal("/four", cdir.find_directory_for_line(9))
		cdir.dir_changes = { [2] = "/new" }
		assert.are.equal("/new", cdir.find_directory_for_line(11))
	end)

	it("updates counts and order on insertion, replacement, removal, and table replacement", function()
		errors.set_error(9, error_at(9))
		errors.set_error(2, error_at(2, nil, errors.level.WARNING))
		errors.set_error(6, error_at(6, nil, errors.level.INFO))
		assert.are.same({ 2, 6, 9 }, errors.ordered_lines())
		assert.are.same({ error = 1, warning = 1, info = 1 }, statusline.info().counts)
		errors.set_error(2, error_at(2))
		errors.set_error(9, nil)
		assert.are.same({ 2, 6 }, errors.ordered_lines())
		assert.are.same({ error = 1, warning = 0, info = 1 }, statusline.info().counts)
		local counts = errors.counts()
		counts.error = 99
		assert.are.equal(1, errors.counts().error)
		errors.error_list = { [5] = error_at(5, nil, errors.level.WARNING) }
		assert.are.same({ 5 }, errors.ordered_lines())
		assert.are.same({ error = 0, warning = 1, info = 0 }, errors.counts())
	end)

	it("refreshes externally edited tables and error records after explicit invalidation", function()
		errors.set_error(5, error_at(5))
		cdir.set_directory(3, "/old")
		errors.counts()
		cdir.find_directory_for_line(10)
		errors.error_list[5].level = errors.level.WARNING
		errors.error_list[8] = error_at(8, nil, errors.level.INFO)
		errors.invalidate()
		assert.are.same({ error = 0, warning = 1, info = 1 }, errors.counts())
		errors.error_list[5] = nil
		errors.invalidate()
		assert.are.same({ 8 }, errors.ordered_lines())
		cdir.dir_changes[3] = "/changed"
		cdir.dir_changes[7] = "/added"
		cdir.invalidate()
		assert.are.equal("/changed", cdir.find_directory_for_line(7))
		assert.are.equal("/added", cdir.find_directory_for_line(8))
		cdir.dir_changes[7] = nil
		cdir.invalidate()
		assert.are.equal("/changed", cdir.find_directory_for_line(8))
	end)

	it("clears ranges once and reparses prefixes without losing retained suffixes", function()
		for _, line in ipairs({ 2, 4, 6, 8, 10 }) do
			errors.set_error(line, error_at(line))
			cdir.set_directory(line, "/dir/" .. line)
		end
		errors.clear_range(1, 6)
		cdir.clear_range(1, 6)
		for _, line in ipairs({ 1, 3, 5 }) do
			errors.set_error(line, error_at(line, nil, errors.level.WARNING))
			cdir.set_directory(line, "/new/" .. line)
		end
		assert.are.same({ 1, 3, 5, 8, 10 }, errors.ordered_lines())
		assert.are.same({ error = 2, warning = 3, info = 0 }, errors.counts())
		assert.are.equal("/new/3", cdir.find_directory_for_line(5))
		assert.are.equal("/new/5", cdir.find_directory_for_line(8))
		assert.are.equal("/dir/8", cdir.find_directory_for_line(9))
		errors.clear_range(3, 8)
		cdir.clear_range(3, 8)
		assert.are.same({ 1, 10 }, errors.ordered_lines())
		assert.are.equal("/new/1", cdir.find_directory_for_line(10))
		errors.clear_range(1, math.huge)
		cdir.clear_range(1, math.huge)
		assert.are.same({}, errors.error_list)
		assert.are.same({}, cdir.dir_changes)
		assert.are.same({ error = 0, warning = 0, info = 0 }, errors.counts())
	end)

	it("tracks trim and reset without retaining stale counts or line indexes", function()
		errors.set_error(5, error_at(5))
		errors.set_error(8, error_at(8, nil, errors.level.WARNING))
		cdir.set_directory(7, "/nested")
		errors.ordered_lines()
		cdir.find_directory_for_line(9)
		state.trim_lines(2)
		assert.are.same({ 6 }, errors.ordered_lines())
		assert.are.equal(6, errors.error_list[6].linenum)
		assert.are.same({ error = 0, warning = 1, info = 0 }, errors.counts())
		assert.are.equal("/nested", cdir.find_directory_for_line(6))
		state.reset()
		assert.are.same({}, errors.ordered_lines())
		assert.are.same({ error = 0, warning = 0, info = 0 }, errors.counts())
		assert.are.equal(cdir.compilation_directory, cdir.find_directory_for_line(6))
	end)

	it("navigates the cached index in both directions with thresholds and circular wrap", function()
		local buf = vim.api.nvim_create_buf(false, true)
		vim.api.nvim_set_current_buf(buf)
		vim.api.nvim_buf_set_lines(buf, 0, -1, false, { "", "", "", "", "", "", "", "" })
		errors.set_error(2, error_at(2, "one.c"))
		errors.set_error(4, error_at(4, "one.c", errors.level.INFO))
		errors.set_error(6, error_at(6, "two.c"))
		errors.set_error(8, error_at(8, "three.c"))
		local silent = { smods = { silent = true } }
		navigation.move_to_next_error(silent)
		assert.are.equal(2, state.error_cursor)
		navigation.move_to_next_error(silent)
		assert.are.equal(6, state.error_cursor)
		navigation.move_to_prev_error(silent)
		assert.are.equal(2, state.error_cursor)
		navigation.move_to_next_file(silent)
		assert.are.equal(6, state.error_cursor)
		navigation.move_to_next_error({ count = 2, smods = { silent = true } })
		assert.are.equal(6, state.error_cursor)
		require("compile-mode.config.internal").use_circular_error_navigation = true
		navigation.move_to_next_error({ count = 2, smods = { silent = true } })
		assert.are.equal(2, state.error_cursor)
		navigation.move_to_prev_error(silent)
		assert.are.equal(8, state.error_cursor)
		assert.are.same({ 2, 4, 6, 8 }, errors.ordered_lines())
	end)
end)

describe("session diagnostics by source file", function()
	local root
	before_each(function()
		helpers.setup_tests()
		state.reset()
		root = vim.fn.getcwd()
		cdir.compilation_directory = root
	end)

	it("invalidates cached files when errors or directory context change", function()
		local original = vim.fn.bufadd(root .. "/first/main.c")
		local replacement = vim.fn.bufadd(root .. "/second/main.c")
		cdir.set_directory(1, root .. "/first")
		errors.set_error(2, error_at(2))
		assert.are.equal(1, #errors.diagnostics_for_buffer(original))
		assert.are.equal(0, #errors.diagnostics_for_buffer(replacement))
		cdir.set_directory(1, root .. "/second")
		assert.are.equal(0, #errors.diagnostics_for_buffer(original))
		assert.are.equal(1, #errors.diagnostics_for_buffer(replacement))
		errors.set_error(2, nil)
		assert.are.same({}, errors.diagnostics_for_buffer(replacement))
		errors.error_list = { [2] = error_at(2) }
		assert.are.equal(1, #errors.diagnostics_for_buffer(replacement))
		cdir.dir_changes = { [1] = root .. "/first" }
		assert.are.equal(1, #errors.diagnostics_for_buffer(original))
		cdir.dir_changes[1] = root .. "/second"
		cdir.invalidate()
		assert.are.equal(1, #errors.diagnostics_for_buffer(replacement))
		state.reset()
		assert.are.same({}, errors.diagnostics_for_buffer(replacement))
	end)

	it("does not reuse resolved paths after changing the compilation directory", function()
		local original = vim.fn.bufadd(root .. "/main.c")
		local replacement = vim.fn.bufadd(root .. "/changed/main.c")
		errors.set_error(2, error_at(2))
		assert.are.equal(1, #errors.diagnostics_for_buffer(original))
		cdir.compilation_directory = root .. "/changed"
		assert.are.equal(0, #errors.diagnostics_for_buffer(original))
		assert.are.equal(1, #errors.diagnostics_for_buffer(replacement))
	end)

	it("keeps source-file groups valid when a source buffer is deleted and recreated", function()
		local filename = root .. "/recreated/main.c"
		local original = vim.fn.bufadd(filename)
		errors.set_error(2, error_at(2, filename))
		assert.are.equal(original, errors.diagnostics_for_buffer(original)[1].bufnr)
		vim.api.nvim_buf_delete(original, { force = true })
		local recreated = vim.fn.bufadd(filename)
		assert.is_true(original ~= recreated)
		assert.are.equal(recreated, errors.diagnostics_for_buffer(recreated)[1].bufnr)
	end)
end)
