local helpers = require("spec.test_helpers")
local errors = require("compile-mode.errors")
local state = require("compile-mode.state")
local utils = require("compile-mode.utils")
local locations = require("compile-mode.source_locations")

describe("visited source locations", function()
	local source, compilation, filename, error
	local namespace = vim.api.nvim_create_namespace("compile-mode.nvim/source-locations")
	local function marks()
		return vim.api.nvim_buf_get_extmarks(source, namespace, 0, -1, {})
	end
	local function jump()
		utils.jump_to_error(error, vim.fn.getcwd(), {})
	end
	before_each(function()
		helpers.setup_tests({ error_locus_highlight = true })
		state.reset()
		filename = vim.fn.tempname() .. ".c"
		vim.fn.writefile({ "first", "abcdef", "last" }, filename)
		source = vim.fn.bufadd(filename)
		vim.fn.bufload(source)
		compilation = vim.api.nvim_create_buf(false, true)
		vim.api.nvim_buf_set_lines(compilation, 0, -1, false, { "diagnostic" })
		vim.g.compilation_buffer = compilation
		vim.api.nvim_set_current_buf(source)
		error = assert(errors.parse(filename .. ":2:2: error: failure", 1))
		error.end_row, error.end_col = { value = 2 }, { value = 4 }
		errors.set_error(1, error)
	end)
	after_each(function()
		locations.reset()
		vim.fn.delete(filename)
	end)

	it("tracks row and byte-column insertions after the first visit", function()
		assert.are.equal(0, #marks())
		jump()
		vim.api.nvim_buf_set_lines(source, 0, 0, false, { "inserted" })
		vim.api.nvim_buf_set_text(source, 2, 0, 2, 0, { "界" })
		jump()
		assert.are.same({ 3, 4 }, vim.api.nvim_win_get_cursor(0))
		local ns = vim.api.nvim_create_namespace("compile-mode.nvim/highlight")
		local highlight = vim.api.nvim_buf_get_extmarks(source, ns, 0, -1, { details = true })[1]
		assert.are.equal(7, highlight[4].end_col)
		assert.are.equal(2, error.row.value)
		assert.are.equal(2, error.col.value)
	end)

	it("does not accumulate marks on repeated navigation", function()
		for _ = 1, 20 do
			jump()
		end
		assert.are.equal(2, #marks())
	end)

	it("preserves original coordinates until the first visit", function()
		vim.api.nvim_buf_set_lines(source, 0, 0, false, { "inserted" })
		jump()
		assert.are.same({ 2, 1 }, vim.api.nvim_win_get_cursor(0))
	end)

	it("follows insertion at the exact locus", function()
		jump()
		vim.api.nvim_buf_set_text(source, 1, 1, 1, 1, { "XYZ" })
		jump()
		assert.are.same({ 2, 4 }, vim.api.nvim_win_get_cursor(0))
	end)

	it("restores the locus after deleting its text and undoing", function()
		jump()
		vim.cmd("normal! dd")
		jump()
		assert.are.same({ 2, 0 }, vim.api.nvim_win_get_cursor(0))
		vim.cmd("silent undo")
		jump()
		assert.are.same({ 2, 1 }, vim.api.nvim_win_get_cursor(0))
	end)

	it("clamps deleted EOF anchors and restores them on undo", function()
		error.row.value, error.col.value = 3, 3
		jump()
		vim.cmd("normal! dd")
		jump()
		assert.are.equal(2, vim.api.nvim_win_get_cursor(0)[1])
		vim.cmd("silent undo")
		jump()
		assert.are.same({ 3, 2 }, vim.api.nvim_win_get_cursor(0))
	end)

	it("discards anchors when a diagnostic is replaced or reparsed", function()
		jump()
		errors.set_error(1, assert(errors.parse(filename .. ":1:1: error: new", 1)))
		assert.are.equal(0, #marks())
		errors.set_error(1, error)
		jump()
		errors.clear_range(1, 1)
		assert.are.equal(0, #marks())
	end)

	it("resets locations for a new compilation", function()
		jump()
		vim.api.nvim_buf_set_lines(source, 0, 0, false, { "inserted" })
		state.reset()
		assert.are.equal(0, #marks())
		jump()
		assert.are.same({ 2, 1 }, vim.api.nvim_win_get_cursor(0))
	end)

	it("reanchors a legacy record whose source coordinates changed", function()
		jump()
		error.row.value = 1
		jump()
		assert.are.same({ 1, 1 }, vim.api.nvim_win_get_cursor(0))
		assert.are.equal(2, #marks())
	end)

	it("reanchors after the source is unloaded and loaded again", function()
		jump()
		vim.api.nvim_buf_set_lines(source, 0, 0, false, { "inserted" })
		vim.api.nvim_set_current_buf(compilation)
		vim.cmd("bunload! " .. source)
		vim.fn.bufload(source)
		assert.are.equal(0, #marks())
		jump()
		assert.are.same({ 2, 1 }, vim.api.nvim_win_get_cursor(0))
	end)

	it("releases discarded errors when output is trimmed", function()
		errors.set_error(1, nil)
		error.linenum = 5
		errors.set_error(5, error)
		vim.api.nvim_buf_set_lines(compilation, 0, -1, false, { "", "", "", "", "error" })
		jump()
		state.trim_lines(1)
		assert.are.equal(0, #marks())
	end)

	it("cleans anchors after legacy replacement and invalidated in-place deletion", function()
		jump()
		errors.error_list = { [1] = error }
		errors.ordered_lines()
		assert.are.equal(2, #marks())
		errors.error_list = {}
		errors.ordered_lines()
		assert.are.equal(0, #marks())
		errors.set_error(1, error)
		jump()
		errors.error_list[1] = nil
		errors.invalidate()
		errors.ordered_lines()
		assert.are.equal(0, #marks())
	end)

	it("releases anchors when a legacy record loses its source row", function()
		jump()
		error.row = nil
		jump()
		assert.are.equal(0, #marks())
	end)
end)
